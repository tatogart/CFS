// Карты строятся на сетке: клетка = CELL метров.
// Легенда клеток:
//  '#' стена            '.' пол             'w' вода (пол)
//  'c' ящик (1м, можно запрыгнуть)          'C' большой ящик (2м)
//  'R' вагон/машина (3.4м)                  'v' пропасть (Vertigo)
//  'T' спавн террористов  'K' спавн спецназа  'A' / 'B' точки закладки
//  '1'..'9' пол с меткой цели гранат (раскидка)
// CELL меняется под карту (у детальных карт клетка мельче)
export let CELL = 3;
export function setCell(v) { CELL = v; }

// R — вырезать прямоугольник, P — поставить клетки, E — высота пола (м),
// S — рампа/лестница: высота меняется линейно от a до b в направлении dir ('N','S','E','W')
function build(w, h, fill, steps) {
  const g = [], el = new Float32Array(w * h);
  for (let j = 0; j < h; j++) g.push(new Array(w).fill(fill));
  const R = (x, y, ww, hh, ch = '.') => {
    for (let j = y; j < y + hh; j++) for (let i = x; i < x + ww; i++)
      if (j >= 0 && j < h && i >= 0 && i < w) g[j][i] = ch;
  };
  const P = (ch, ...pts) => { for (let k = 0; k < pts.length; k += 2) g[pts[k + 1]][pts[k]] = ch; };
  const E = (x, y, ww, hh, lv) => { for (let j = y; j < y + hh; j++) for (let i = x; i < x + ww; i++) if (j >= 0 && j < h && i >= 0 && i < w) el[j * w + i] = lv; };
  const S = (x, y, ww, hh, dir, a, b) => {
    const n = dir === 'N' || dir === 'S' ? hh : ww;
    for (let j = y; j < y + hh; j++) for (let i = x; i < x + ww; i++) {
      if (j < 0 || j >= h || i < 0 || i >= w) continue;
      const k = dir === 'E' ? i - x : dir === 'W' ? x + ww - 1 - i : dir === 'S' ? j - y : y + hh - 1 - j;
      el[j * w + i] = n > 1 ? a + (b - a) * k / (n - 1) : b;
    }
  };
  steps(R, P, E, S);
  const out = g.map(r => r.join('')); out.elev = el;
  return out;
}

